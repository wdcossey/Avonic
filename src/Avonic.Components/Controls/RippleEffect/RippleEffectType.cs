/// Ionic <c>ion-ripple-effect</c> <c>type</c>.
/// </summary>
public enum RippleEffectType
{
    /// <summary>The ripple expands from the press position and is clipped to the host's bounds.</summary>
    Bounded,

    /// <summary>The ripple expands from the centre of the host and may overflow it.</summary>
    Unbounded,
}
