namespace Avonic.Components.Controls;

/// <summary>Ionic <c>ion-toggle</c> <c>justify</c>: how the label and track are packed along the line.</summary>
public enum ToggleJustify
{
    /// <summary>At the end of the line: the right in LTR, and the left in RTL.</summary>
    End,

    /// <summary>At opposite ends of the line, with the space between them.</summary>
    SpaceBetween,

    /// <summary>At the start of the line: the left in LTR, and the right in RTL.</summary>
    Start,
}
