namespace Avonic.Components.Controls;

/// <summary>The visual fill style of an <see cref="AvonicButton"/>.</summary>
public enum ButtonFill
{
    /// <summary>Filled background using the button colour (default).</summary>
    Solid,

    /// <summary>Transparent background with a coloured border.</summary>
    Outline,

    /// <summary>Transparent background and no border — text only.</summary>
    Clear,
}
