namespace Avonic.Components.Controls.Enums;

/// <summary>
/// Controls the visual fill style of the input container.
/// </summary>
/// <remarks>
/// Ionic reference: <c>ion-input</c> / <c>ion-textarea</c> <c>fill</c> prop.
/// </remarks>
public enum InputFill
{
    /// <summary>No background fill, no explicit border (default).</summary>
    Default,

    /// <summary>Solid background fill (muted surface).</summary>
    Solid,

    /// <summary>Transparent background with a full border outline.</summary>
    Outline,
}
