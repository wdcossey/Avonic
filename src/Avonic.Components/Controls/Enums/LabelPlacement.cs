namespace Avonic.Components.Controls.Enums;

/// <summary>
/// Controls where the label is rendered relative to the interactive control element.
/// </summary>
/// <remarks>
/// Ionic reference: <c>label-placement</c> prop on ion-checkbox, ion-toggle, ion-radio.
/// </remarks>
public enum LabelPlacement
{
    /// <summary>Label is rendered after (to the right of) the control element. Default.</summary>
    End,

    /// <summary>Label is rendered before (to the left of) the control element.</summary>
    Start,

    /// <summary>Label is rendered above the control element, control is centred below.</summary>
    Stacked,
}
