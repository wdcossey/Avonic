namespace Avonic.Components.Controls.Enums;

/// <summary>
/// Controls the cross-axis alignment of the label and interactive control.
/// </summary>
/// <remarks>
/// Ionic reference: <c>alignment</c> prop on ion-checkbox, ion-toggle, ion-radio.
/// </remarks>
public enum CheckableAlignment
{
    /// <summary>The label and control are centred on the cross axis. Default.</summary>
    Center,

    /// <summary>The label and control are aligned to the start of the cross axis.</summary>
    Start,
}
