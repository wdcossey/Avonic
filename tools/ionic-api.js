#!/usr/bin/env node
// Prints the complete public API of an Ionic component from @ionic/docs core.json
// as a Markdown fidelity checklist. This is the spec every Avonic control is built from.
//
//   node tools/ionic-api.js ion-item            # markdown checklist
//   node tools/ionic-api.js ion-item --json     # raw JSON subset
//   node tools/ionic-api.js --list              # all 95 tags
//
// Reference material (none of this is in the repo; `npm install` fetches it):
//   node_modules/@ionic/docs/core.json
//   node_modules/@ionic/core/dist/collection/components/<name>/<name>.js      (readable implementation)
//   node_modules/@ionic/core/dist/collection/components/<name>/<name>.md.css  (base skin we recreate)

const path = require('path');
const fs = require('fs');

const corePath = path.join(__dirname, '..', 'node_modules', '@ionic', 'docs', 'core.json');
if (!fs.existsSync(corePath)) {
    console.error('core.json not found — run `npm install` first.');
    process.exit(1);
}
const core = JSON.parse(fs.readFileSync(corePath, 'utf8'));

const args = process.argv.slice(2);
if (args.includes('--list')) {
    console.log(core.components.map(c => c.tag).join('\n'));
    process.exit(0);
}

const tag = args.find(a => !a.startsWith('--'));
if (!tag) {
    console.error('usage: node tools/ionic-api.js <ion-tag> [--json]');
    process.exit(1);
}
const c = core.components.find(x => x.tag === tag);
if (!c) {
    console.error(`unknown component "${tag}" — try --list`);
    process.exit(1);
}

// CSS vars are listed once per mode; we keep md as the base and note ios-only ones.
const cssVars = new Map();
for (const s of c.styles) {
    const e = cssVars.get(s.name) ?? { name: s.name, docs: s.docs, modes: new Set() };
    e.modes.add(s.mode);
    cssVars.set(s.name, e);
}

const subset = {
    tag: c.tag,
    file: `node_modules/@ionic/core/dist/collection/components/${c.tag.replace(/^ion-/, '')}/${c.tag.replace(/^ion-/, '')}.js`,
    docs: c.docs,
    props: c.props.map(p => ({ name: p.name, type: p.type, default: p.default, docs: p.docs })),
    events: c.events.map(e => ({ name: e.event, detail: e.detail, docs: e.docs })),
    methods: c.methods.map(m => ({ name: m.name, signature: m.signature, docs: m.docs })),
    slots: c.slots.map(s => ({ name: s.name || '(default)', docs: s.docs })),
    parts: c.parts.map(p => ({ name: p.name, docs: p.docs })),
    cssVars: [...cssVars.values()].map(v => ({ name: v.name, docs: v.docs, modes: [...v.modes].sort() })),
    dependencies: c.dependencies,
};

if (args.includes('--json')) {
    console.log(JSON.stringify(subset, null, 2));
    process.exit(0);
}

const pascal = s => s.replace(/(^|-)([a-z])/g, (_, __, ch) => ch.toUpperCase());
// The one renamed prop: Avalonia already has IsEnabled on every control (see CLAUDE.md mapping rules).
const propName = p => p === 'disabled' ? 'IsEnabled (inverted)' : pascal(p);
const cssKey = name => {
    // --ion-color-primary        → Avonic.Color.Primary
    // --background (on ion-item) → Avonic.Item.Background
    if (name.startsWith('--ion-color-')) return `Avonic.Color.${pascal(name.slice('--ion-color-'.length))}`;
    if (name.startsWith('--ion-'))       return `Avonic.${pascal(name.slice('--ion-'.length))}`;
    return `Avonic.${pascal(c.tag.replace(/^ion-/, ''))}.${pascal(name.slice(2))}`;
};
const code = s => '`' + String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ') + '`';
const text = s => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ');

const out = [];
out.push(`# ${c.tag} — fidelity checklist`);
out.push('');
out.push(`> Generated by \`node tools/ionic-api.js ${c.tag}\` from @ionic/docs core.json.`);
out.push(`> Implementation reference: \`${subset.file}\``);
out.push('');
out.push(text(c.docs));
out.push('');

const section = (title, rows, header) => {
    out.push(`## ${title} (${rows.length})`);
    out.push('');
    if (!rows.length) { out.push('_none_'); out.push(''); return; }
    out.push(header);
    out.push(header.replace(/[^|]/g, '-'));
    rows.forEach(r => out.push(r));
    out.push('');
};

section('Props', subset.props.map(p =>
    `| [ ] | ${code(p.name)} | ${code(propName(p.name))} | ${code(p.type)} | ${code(p.default)} | ${text(p.docs)} |`),
    '| ✓ | Ionic | Avonic | Type | Default | Docs |');

section('Events', subset.events.map(e =>
    `| [ ] | ${code(e.name)} | ${code(pascal(e.name))} | ${code(e.detail)} | ${text(e.docs)} |`),
    '| ✓ | Ionic | Avonic | Detail | Docs |');

section('Methods', subset.methods.map(m =>
    `| [ ] | ${code(m.signature)} | ${code(pascal(m.name) + '()')} | ${text(m.docs)} |`),
    '| ✓ | Ionic | Avonic | Docs |');

section('Slots', subset.slots.map(s =>
    `| [ ] | ${code(s.name)} | ${code(s.name === '(default)' ? 'Content' : pascal(s.name) + 'Content')} | ${text(s.docs)} |`),
    '| ✓ | Ionic | Avonic | Docs |');

section('Shadow parts', subset.parts.map(p =>
    `| [ ] | ${code(p.name)} | ${code('PART_' + pascal(p.name))} | ${text(p.docs)} |`),
    '| ✓ | Ionic | Avonic template name | Docs |');

section('CSS custom properties → resource keys', subset.cssVars.map(v =>
    `| [ ] | ${code(v.name)} | ${code(cssKey(v.name))} | ${v.modes.join(', ')} | ${text(v.docs)} |`),
    '| ✓ | Ionic | Avonic resource key | Modes | Docs |');

if (subset.dependencies.length) {
    out.push(`## Depends on`);
    out.push('');
    subset.dependencies.forEach(d => out.push(`- ${code(d)}`));
    out.push('');
}

console.log(out.join('\n'));
